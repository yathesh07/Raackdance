// Generates supabase/seed.sql from the migrated content (src/content → src/lib/seed.ts).
// Run: npm run seed:sql
import { writeFileSync } from 'node:fs'
import { buildSeed } from '../src/lib/seed'

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null'
  if (Array.isArray(v) && v.every((x) => typeof x === 'string')) return v.length ? `array[${v.map((x) => lit(x)).join(',')}]::text[]` : `'{}'::text[]`
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`
  return `'${String(v).replace(/'/g, "''")}'`
}
const JSONB = new Set(['highlights', 'stat', 'value'])
const seed = buildSeed() as unknown as Record<string, Record<string, unknown>[]>
const order = ['programs', 'studios', 'branch_heads', 'class_sessions', 'team_members', 'events', 'testimonials', 'media', 'careers', 'site_settings', 'pages']
let sql = `-- Generated by scripts/generate-seed.ts from content migrated off raackdance.com. Safe to re-run (on conflict do nothing).\nbegin;\n`
for (const t of order) {
  const rows = seed[t] ?? []
  if (!rows.length) continue
  const cols = Object.keys(rows[0])
  const key = t === 'site_settings' ? 'key' : t === 'pages' ? 'slug' : 'id'
  sql += `\n-- ${t} (${rows.length})\ninsert into public.${t} (${cols.join(', ')}) values\n`
  sql += rows.map((r) => `(${cols.map((c) => (JSONB.has(c) ? (r[c] == null ? 'null' : `'${JSON.stringify(r[c]).replace(/'/g, "''")}'::jsonb`) : lit(r[c]))).join(', ')})`).join(',\n')
  sql += `\non conflict (${key}) do nothing;\n`
}
sql += '\ncommit;\n'
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log('supabase/seed.sql written')
